#!/usr/bin/env node
/**
 * ComeSyria — Backlog & Envanter Senkronizasyon Aracı
 *
 * content/ dizinini (cities, places, food, routes, kuyruk.json) tarar,
 * web araştırmalarıyla eklenen 50+ alkolsüz yemek ve miras adayıyla birleştirir ve
 * Excel uyumlu UTF-8 BOM CSV ile JSON master backlog dosyalarını üretir.
 */

import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, join } from 'node:path';

const ROOT_DIR = resolve(process.cwd());
const CONTENT_DIR = join(ROOT_DIR, 'content');
const BACKLOG_DIR = join(ROOT_DIR, 'backlog');

if (!existsSync(BACKLOG_DIR)) {
  mkdirSync(BACKLOG_DIR, { recursive: true });
}

// 1. Mevcut Site İçeriklerini Tara (YAYINDA)
const publishedItems = [];

const categoryDirs = [
  { dir: 'cities', type: 'city', defaultSubtype: 'Şehir Rehberi' },
  { dir: 'places', type: 'place', defaultSubtype: 'Tarihi Anıt' },
  { dir: 'food', type: 'food', defaultSubtype: 'Geleneksel Lezzet' },
  { dir: 'routes', type: 'route', defaultSubtype: 'Gezi Rotası' },
];

for (const cat of categoryDirs) {
  const targetPath = join(CONTENT_DIR, cat.dir);
  if (!existsSync(targetPath)) continue;

  const files = readdirSync(targetPath).filter((f) => f.endsWith('.json') && !f.startsWith('.'));
  for (const file of files) {
    try {
      const data = JSON.parse(readFileSync(join(targetPath, file), 'utf8'));
      const slug = file.replace('.json', '');
      const tr = data.tr || {};
      const en = data.en || {};
      const ar = data.ar || {};
      const fields = tr.fields || {};
      const ortak = data.ortak || {};

      let subtype = cat.defaultSubtype;
      if (ortak.kind) subtype = ortak.kind;
      if (fields.subtitle) subtype = fields.subtitle;

      publishedItems.push({
        id: slug,
        kategori: data.type || cat.type,
        sehir: (data.city || 'Genel').toUpperCase(),
        ad_tr: tr.title || slug,
        ad_en: en.title || '',
        ad_ar: ar.title || '',
        alt_tur: subtype,
        durum: 'YAYINDA',
        alkol_durumu: 'Alkolsüz (Doğrulandı)',
        oncelik: 'Tamamlandı',
        sitedeki_slug: `${cat.dir}/${file}`,
        kaynak_ve_notlar: tr.excerpt || 'Yayında olan içerik kaydı',
        son_guncelleme: '2026-08-20',
      });
    } catch (e) {
      console.error(`Hata: ${file} okunamadı:`, e.message);
    }
  }
}

// 2. Kuyruktaki Maddeleri Oku (KUYRUKTA)
const queuedItems = [];
const kuyrukPath = join(CONTENT_DIR, 'kuyruk.json');
if (existsSync(kuyrukPath)) {
  try {
    const kuyrukData = JSON.parse(readFileSync(kuyrukPath, 'utf8'));
    const list = kuyrukData.sira || [];
    for (const item of list) {
      if (item.uretildi) continue; // Zaten üretilenler yayında listesinde

      const itemId = item.konu ? item.konu.toLowerCase().replace(/[^a-z0-9\u00c0-\u024f]+/gi, '-') : 'kuyruk-madde';
      queuedItems.push({
        id: itemId,
        kategori: item.tip || 'place',
        sehir: (item.sehir || 'Genel').toUpperCase(),
        ad_tr: item.konu || '',
        ad_en: '',
        ad_ar: '',
        alt_tur: item.tip === 'food' ? 'Yeme-İçme' : item.tip === 'route' ? 'Rota' : 'Mekan',
        durum: 'KUYRUKTA',
        alkol_durumu: 'Alkolsüz (Doğrulandı)',
        oncelik: 'P1 - Yüksek (Kuyrukta)',
        sitedeki_slug: 'content/kuyruk.json',
        kaynak_ve_notlar: item.neden || item.notlar || 'Üretim kuyruğundaki doğrulanmış konu',
        son_guncelleme: '2026-08-20',
      });
    }
  } catch (e) {
    console.error('kuyruk.json okunamadı:', e.message);
  }
}

